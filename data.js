/* ---------- 形状ヘルパ ---------- */

/** 矩形をポリゴン（頂点配列）に */
function rect(x, y, w, h) {
  return [[x, y], [x + w, y], [x + w, y + h], [x, y + h]];
}

/**
 * 段構成からセル列を生成する。
 * tiers: [{ h: 段の高さ比, cols: [コマの幅比, ...] }, ...]
 * cols は右から左の順で並べる（読み順と同じ）。h と cols の値は比率で、
 * 合計が 1 でなくても自動で正規化される。
 */
function tiersToCells(tiers) {
  const cells = [];
  const totalH = tiers.reduce((s, t) => s + t.h, 0);
  let y = 0;
  for (const t of tiers) {
    const h = t.h / totalH;
    const totalW = t.cols.reduce((s, w) => s + w, 0);
    let xRight = 1;
    for (const w of t.cols) {
      const cw = w / totalW;
      cells.push(rect(xRight - cw, y, cw, h));
      xRight -= cw;
    }
    y += h;
  }
  return cells;
}

/** シグネチャとタグを形状から補って1件分のパターンにする */
function makeLayout(id, panels, name, cells, note, est) {
  return {
    id, panels, name, cells, note, est,
    sig: signatureFromBoxes(cells.map(bboxOf)),
    tags: autoTags(cells),
  };
}

/** 段構成ベースのパターン */
function T(id, panels, name, tiers, note, est) {
  return makeLayout(id, panels, name, tiersToCells(tiers), note, est);
}

/** ポリゴン直指定のパターン（斜め・重ねゴマ用） */
function P(id, panels, name, cells, note, est) {
  return makeLayout(id, panels, name, cells, note, est);
}

